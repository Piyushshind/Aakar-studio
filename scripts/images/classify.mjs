const HERO_EDGE = 2400;
const FULLBLEED_EDGE = 1800;
const GRID_EDGE = 1000;
// Peak tile sharpness at 2400px; faces at >= 150 were confirmed crisp by eye.
const SHARP_ENOUGH = 150;

function tier(r) {
  if (r.longEdge >= HERO_EDGE && r.peakSharpness >= SHARP_ENOUGH) return 'hero';
  if (r.longEdge >= FULLBLEED_EDGE) return 'fullbleed';
  if (r.longEdge >= GRID_EDGE) return 'grid';
  return 'small';
}

const inventory = await readJson(path.join(OUT_DIR, 'inventory.json'));
const { keepers } = await readJson(path.join(OUT_DIR, 'duplicates.json'));
const byName = new Map(inventory.map((r) => [r.fileName, r]));

const problems = [];
const entries = TABLE.map(
  ([file, category, kind, theme, album, albumOrder, subject, alt, flags = '', notes = '']) => {
    const r = byName.get(file);
    if (!r) problems.push(`not in inventory: ${file}`);
    else if (!keepers.includes(file)) problems.push(`not a keeper: ${file}`);
    if (alt.length > 125) problems.push(`alt too long (${alt.length}): ${file}`);
    return {
      sourcePath: r?.relPath ?? file,
      category,
      kind,
      theme,
      album,
      albumOrder,
      subject,
      alt,
      orientation: r?.orientation ?? null,
      width: r?.width ?? null,
      height: r?.height ?? null,
      hasWatermark: flags.includes('w'),
      hasTextOverlay: flags.includes('t'),
      isChild: flags.includes('c'),
      qualityTier: r ? tier(r) : null,
      featuredCandidate: flags.includes('f'),
      heroCandidate: flags.includes('H'),
      needsReview: flags.includes('r') || category === '_review',
      notes,
    };
  },
);

const classified = new Set(TABLE.map((t) => t[0]));
for (const k of keepers) if (!classified.has(k)) problems.push(`keeper not classified: ${k}`);
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

await writeOut(path.join(OUT_DIR, 'classification.json'), JSON.stringify(entries, null, 2));
log(`classified ${entries.length} keepers`);
