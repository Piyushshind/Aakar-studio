import { useId } from 'react';
import { cn } from '@/lib/cn';
import { logoArt } from './logoArt';

export type LogoVariant = 'horizontal' | 'stacked' | 'mark' | 'tagline';
export type LogoTone = 'light' | 'dark';

interface LogoProps {
  variant?: LogoVariant;
  /** light = cream text for dark backgrounds, dark = brown text for cream/white backgrounds. */
  tone?: LogoTone;
  /** Mark only: the simplified mark for 32–48 px. */
  simple?: boolean;
  /** Mark only: gold A and lens without the camera, for 16–24 px. */
  tiny?: boolean;
  className?: string;
  title?: string;
}

/**
 * The studio logo as inline SVG (spec 4.6), generated by `pnpm brand:build` into ./logoArt.ts.
 * Gold always uses the gradients; the ink (camera outline and text) follows `tone` through
 * currentColor. Animatable parts carry classes: a-letter, a-strokes, a-swash, camera,
 * camera-body, lens, lens-rim, lens-glass, wordmark, label, rules, tagline. Ids (including the
 * gradients) are prefixed per instance, so several logos can share a page.
 */
export function Logo({
  variant = 'horizontal',
  tone = 'light',
  simple = false,
  tiny = false,
  className,
  title = 'Aakar Digital Photo Studio',
}: LogoProps) {
  const prefix = `aakar-${useId().replace(/[^\w-]/g, '')}-`;
  const art =
    logoArt[
      variant === 'mark' && tiny
        ? 'mark-tiny'
        : variant === 'mark' && simple
          ? 'mark-simple'
          : variant
    ];
  const titleId = `${prefix}title`;

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={art.viewBox}
      role="img"
      aria-labelledby={titleId}
      className={cn('block h-auto', tone === 'light' ? 'text-text' : 'text-brown', className)}
    >
      <title id={titleId}>{title}</title>
      {/* Generated, trusted markup from scripts/brand/build.mjs (no user input). */}
      <g dangerouslySetInnerHTML={{ __html: art.markup.replaceAll('__ID__', prefix) }} />
    </svg>
  );
}
